def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--libritts", required=True, help="LibriTTS test-clean 根目录")
    ap.add_argument("--out", default="dataset/libritts16k", help="输出目录")
    args = ap.parse_args()

    root = Path(args.libritts)
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)

    missing = []
    done = 0
    for name in FILES:
        # libritts16k 命名：{spk}_{book}_{spk}_{book}_{utt}_{seg}
        parts = name.split("_")
        spk, book = parts[0], parts[1]
        # 源文件（LibriTTS 原生命名）：{spk}_{book}_{utt}_{seg}
        src_name = "_".join(parts[:2] + parts[4:])
        src = root / spk / book / f"{src_name}.wav"
        if not src.exists():
            missing.append(str(src))
            continue
        w, sr = librosa.load(str(src), sr=16000, mono=True)
        sf.write(str(out / f"{name}.wav"), w, 16000)
        done += 1

    print(f"完成：{done}/{len(FILES)} 个文件写入 {out}/")
    if missing:
        print(f"缺失 {len(missing)} 个源文件（检查 --libritts 路径）：")
        for m in missing[:10]:
            print(f"  {m}")


if __name__ == "__main__":
    main()
